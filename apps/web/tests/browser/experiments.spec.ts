import { test, expect, type BrowserContext } from '@playwright/test';
import { createHmac, randomUUID } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import { PrismaClient } from '@prisma/client';
import { PrismaPg } from '@prisma/adapter-pg';
import { getCookies } from 'better-auth/cookies';
import type { LabReviewInput, LabStudy, LabStudySummary } from '../../features/experiments/types';
import { capture, screenshots, noHorizontalOverflow } from './support/ui';

// Only explicit local identities are used. No OAuth bypass exists in the app.
const ownerId = 'experiment-qa-local';
const peerId = 'experiment-qa-peer';

test('private experiment images, independent reviews, persistence and workspace', async ({ browser, baseURL }) => {
  test.skip(process.env.RUN_EXPERIMENT_BROWSER !== '1', 'Opt in to local disposable experiment sessions.');
  const database = new URL(process.env.DATABASE_URL!);
  if (!['localhost', '127.0.0.1'].includes(database.hostname)) throw new Error('Experiment browser fixtures require a local database.');
  const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: database.toString(), max: 2 }) });
  const created: string[] = [], contexts: BrowserContext[] = [];
  const origin = new URL(baseURL!).origin;
  async function session(userId: string, allowed: boolean) {
    if (await db.user.findUnique({ where: { id: userId } })) throw new Error(`Refusing to replace existing fixture identity ${userId}.`);
    await db.user.create({ data: { id: userId, name: allowed ? 'Experimentos · teste local' : 'Sem acesso', email: `${userId}@example.invalid`, emailVerified: true } });
    created.push(userId);
    const token = randomUUID();
    await db.session.create({ data: { id: randomUUID(), token, userId, expiresAt: new Date(Date.now() + 3600_000) } });
    const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } });
    contexts.push(context);
    const cookie = getCookies({ baseURL, secret: process.env.BETTER_AUTH_SECRET }).sessionToken;
    const signature = createHmac('sha256', process.env.BETTER_AUTH_SECRET!).update(token).digest('base64');
    await context.addCookies([{ name: cookie.name, value: encodeURIComponent(`${token}.${signature}`), url: baseURL!, httpOnly: true, sameSite: 'Lax' }]);
    return context;
  }
  try {
    const owner = await session(ownerId, true), peer = await session(peerId, true);
    const denied = await session(`experiment-denied-${randomUUID()}`, false);
    const anonymous = await browser.newContext({ baseURL }); contexts.push(anonymous);
    expect((await owner.request.get('/api/experiments/access')).status()).toBe(200);
    expect(await (await owner.request.get('/api/experiments/access')).json()).toEqual({ allowed: true });
    expect(await (await denied.request.get('/api/experiments/access')).json()).toEqual({ allowed: false });
    expect((await anonymous.request.get('/api/experiments')).status()).toBe(401);
    expect((await denied.request.get('/api/experiments')).status()).toBe(403);
    const listed = await owner.request.get('/api/experiments'); expect(listed.status()).toBe(200);
    const studies = (await listed.json()).studies as LabStudySummary[];
    expect(studies.length).toBeGreaterThan(0);
    const id = studies[0].id, endpoint = `/api/experiments/${id}`;
    const response = await owner.request.get(endpoint); expect(response.status()).toBe(200);
    expect(response.headers()['cache-control']).toContain('no-store');
    const study = await response.json() as LabStudy;
    expect(study).not.toHaveProperty('assets');
    expect(JSON.stringify(study)).not.toContain('.lab-data');
    expect(study.candidateCount).toBe(346);
    expect(study.sampleCount).toBe(300);
    const assetUrl = `${endpoint}/assets/${study.regions[0].scenes[0].rgbAssetId}`;
    expect((await anonymous.request.get(assetUrl)).status()).toBe(401);
    expect((await denied.request.get(assetUrl)).status()).toBe(403);
    const image = await owner.request.get(assetUrl); expect(image.status()).toBe(200);
    expect(image.headers()['content-type']).toMatch(/^image\/(jpeg|png)/);
    expect(image.headers()['cache-control']).toContain('private');
    expect((await owner.request.get(`${endpoint}/assets/not-in-the-bundle`)).status()).toBe(404);
    const sample = study.samples.find(item => item.usable)!;
    const input: LabReviewInput = { sampleId: sample.id, decision: 'class', label: 1, certainty: 'high', notes: 'Fixture local descartável', referenceKind: 'human_visual_interpretation', blindReview: true, expectedRevision: 0 };
    const put = (data: unknown, extraHeaders: Record<string, string> = {}) => owner.request.put(`${endpoint}/reviews`, { data, headers: { origin, ...extraHeaders } });
    for (const [body, status] of [['{', 400], ['[]', 422], ['{}', 422], [JSON.stringify({ notes: 'x'.repeat(17_000) }), 413]] as const) {
      expect((await put(Buffer.from(body), { 'content-type': 'application/json' })).status()).toBe(status);
    }
    expect((await put(input, { 'content-type': 'text/plain' })).status()).toBe(415);
    expect((await put(input, { origin: 'https://unrelated.example' })).status()).toBe(403);
    expect((await put({ ...input, sampleId: 'unknown-sample' })).status()).toBe(404);
    const first = await put(input); expect(first.status()).toBe(200);
    expect((await first.json()).review.revision).toBe(1);
    const race = await Promise.all([put({ ...input, expectedRevision: 1, notes: 'Revision A' }), put({ ...input, expectedRevision: 1, notes: 'Revision B' })]);
    expect(race.map(item => item.status()).sort()).toEqual([200, 409]);
    const peerReviews = await (await peer.request.get(`${endpoint}/reviews`)).json();
    expect(peerReviews.reviews).toEqual([]);
    expect(peerReviews.totalReviewCount).toBeGreaterThanOrEqual(1);
    expect(peerReviews.myReviewedCount).toBe(0);
    const ownReviews = await (await owner.request.get(`${endpoint}/reviews`)).json();
    expect(ownReviews.reviews).toHaveLength(1);
    expect(ownReviews.reviews[0].revision).toBe(2);
    const exported = await owner.request.get(`${endpoint}/reviews/export`); expect(exported.status()).toBe(200);
    const annotation = await exported.json();
    const labeled = annotation.samples.filter((item: { label: number | null }) => item.label !== null);
    expect(labeled).toHaveLength(1);
    expect(labeled[0]).toMatchObject({ id: sample.id, row: sample.row, col: sample.col, target_scene_id: sample.targetSceneId, reference_kind: 'human_visual_interpretation' });
    const unblind = await put({ ...input, blindReview: false, expectedRevision: 2 }); expect(unblind.status()).toBe(200);
    const withoutUnblind = await (await owner.request.get(`${endpoint}/reviews/export`)).json();
    expect(withoutUnblind.samples.filter((item: { label: number | null }) => item.label !== null)).toHaveLength(0);

    const page = await owner.newPage(), errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('/experiments');
    await expect(page.getByRole('link', { name: 'Experimentação', exact: true }).first()).toBeVisible();
    await expect(page.getByRole('heading', { name: study.title, exact: true })).toBeVisible();
    await page.goto(`/experiments/${id}`);
    await expect(page.getByRole('tab', { name: 'Explorar', exact: true })).toBeVisible();
    await expect(page.locator('.leaflet-image-layer').first()).toBeVisible();
    await expect.poll(() => page.locator('.leaflet-image-layer').first().evaluate((element: HTMLImageElement) => element.complete && element.naturalWidth > 0)).toBe(true);
    const oldImage = await page.locator('.leaflet-image-layer').first().getAttribute('src');
    await page.getByRole('button', { name: 'Camadas', exact: true }).click();
    await page.getByRole('combobox', { name: 'Visualização da imagem', exact: true }).selectOption('falseColor');
    await expect.poll(() => page.locator('.leaflet-image-layer').first().getAttribute('src')).not.toBe(oldImage);
    const opacity = page.getByRole('slider', { name: 'Opacidade da imagem de comparação', exact: true });
    await opacity.focus(); await page.keyboard.press('Home'); await expect(opacity).toHaveValue('0');
    await page.keyboard.press('End'); await expect(opacity).toHaveValue('1');
    await expect(page.locator('img[data-geospatial-layer="comparison"]')).toHaveCSS('opacity', '1');
    await page.keyboard.press('Escape');
    const minimum = page.getByRole('spinbutton', { name: 'Área mínima dos candidatos', exact: true });
    await minimum.fill('999999');
    await expect(page.getByText('Nenhum candidato atende a esses filtros.', { exact: true })).toBeVisible();
    await minimum.fill('0.5');
    await page.getByTestId('experiment-candidate').first().click();
    await expect(page.getByText('Não determinada', { exact: true })).toBeVisible();
    await expect(page.locator('.leaflet-interactive[stroke="#f1e9cf"]')).toHaveCount(1);
    await page.getByRole('combobox', { name: 'Piloto do estudo', exact: true }).selectOption(study.regions[1].id);
    await expect(page.getByTestId('experiment-candidate')).toHaveCount(study.regions[1].metrics.candidateCount);
    await mkdir(screenshots, { recursive: true });
    await noHorizontalOverflow(page);
    await capture(page, 'experiments-map-desktop.png');
    await page.getByRole('tab', { name: 'Revisar amostras', exact: true }).click();
    await expect(page.getByRole('button', { name: /Salvar revisão/ })).toBeVisible();
    await page.getByRole('button', { name: 'Pastagem', exact: true }).click();
    const notes = page.getByRole('textbox', { name: 'Observações', exact: true });
    await notes.fill('Revisão feita pela interface');
    await page.getByRole('checkbox', { name: /Declaro que interpretei/ }).check();
    await page.getByRole('button', { name: 'Salvar revisão', exact: true }).click();
    await expect(page.getByText(/Revisão salva/)).toBeVisible();
    await page.reload();
    await page.getByRole('tab', { name: 'Revisar amostras', exact: true }).click();
    await expect(notes).toHaveValue('Revisão feita pela interface');
    await expect(page.getByRole('button', { name: 'Pastagem', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await notes.fill('Rascunho que deve ser preservado');
    await page.getByRole('button', { name: 'Próxima amostra', exact: true }).click();
    await expect(page.getByRole('alertdialog')).toBeVisible();
    await page.getByRole('button', { name: 'Continuar editando', exact: true }).click();
    await expect(notes).toHaveValue('Rascunho que deve ser preservado');
    await page.getByRole('button', { name: 'Próxima amostra', exact: true }).click();
    await page.getByRole('button', { name: 'Descartar e continuar', exact: true }).click();
    await page.getByRole('checkbox', { name: 'Apenas minhas pendentes', exact: true }).check();
    const concurrentSample = study.samples.find(item => item.id !== sample.id && item.usable)!;
    await expect(page.getByRole('heading', { name: new RegExp(concurrentSample.id) })).toBeVisible();
    await page.getByRole('button', { name: 'Floresta', exact: true }).click();
    await notes.fill('Rascunho local preservado após conflito');
    expect((await put({ ...input, sampleId: concurrentSample.id, notes: 'Salvo em outra aba' })).status()).toBe(200);
    await page.getByRole('button', { name: 'Salvar revisão', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Carregar versão salva', exact: true })).toBeVisible();
    await expect(notes).toHaveValue('Rascunho local preservado após conflito');
    await expect(page.getByRole('heading', { name: new RegExp(concurrentSample.id) })).toBeVisible();
    await page.getByRole('button', { name: 'Carregar versão salva', exact: true }).click();
    await page.getByRole('button', { name: 'Descartar e continuar', exact: true }).click();
    await expect(notes).toHaveValue('Salvo em outra aba');
    await noHorizontalOverflow(page);
    await capture(page, 'experiments-review-desktop.png');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await noHorizontalOverflow(page);
    await capture(page, 'experiments-review-mobile.png');
    const enlarge = page.getByRole('button', { name: /^Ampliar imagem:/ }).first();
    await enlarge.click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await expect.poll(() => page.getByRole('dialog').getByRole('img', { name: /da amostra/ }).evaluate((element: HTMLImageElement) => element.complete && element.naturalWidth > 0)).toBe(true);
    await noHorizontalOverflow(page);
    await capture(page, 'experiments-image-mobile.png');
    await page.keyboard.press('Escape');
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(enlarge).toBeFocused();
    await page.getByRole('tab', { name: 'Explorar', exact: true }).click();
    const explore = page.getByTestId('experiment-explore');
    await expect.poll(() => explore.evaluate(element => getComputedStyle(element).overflowY)).toBe('auto');
    await page.getByTestId('experiment-candidate').first().click();
    await page.getByText('Não determinada', { exact: true }).scrollIntoViewIfNeeded();
    await expect(page.getByText('Não determinada', { exact: true })).toBeInViewport();
    await noHorizontalOverflow(page);
    await capture(page, 'experiments-candidate-mobile.png');
    await page.getByRole('tab', { name: 'Resultados e método', exact: true }).click();
    await noHorizontalOverflow(page);
    await capture(page, 'experiments-results-mobile.png');
    await page.getByRole('tab', { name: 'Pesquisas', exact: true }).click();
    await expect(page.getByRole('link', { name: study.papers[0].title, exact: true })).toBeVisible();
    expect(errors).toEqual([]);

    await db.session.deleteMany({ where: { userId: ownerId } });
    expect((await owner.request.get(endpoint)).status()).toBe(401);
    expect((await owner.request.get(assetUrl)).status()).toBe(401);
  } finally {
    for (const context of contexts) await context.close();
    // Cascades remove only reviews and sessions belonging to identities created above.
    await db.user.deleteMany({ where: { id: { in: created } } });
    await db.$disconnect();
  }
});
